export const getUpazilasForDistrict = (districtName: string): string[] => {
  if (!districtName) return ['উপজেলা নির্বাচন করুন'];
  const list = DISTRICT_UPAZILAS[districtName.trim()];
  if (list && list.length > 0) {
    return list;
  }
  return ['সদর', 'অন্যান্য'];
};

export const isDhakaDistrict = (districtName: string): boolean => {
  if (!districtName) return false;
  const normalized = districtName.trim().toLowerCase();
  return normalized === 'ঢাকা' || normalized === 'dhaka';
};
