export const getOfferProducts = (): Product[] => {
  return PRODUCTS_CATALOG.filter((p) => p.isOffer);
};

export const getProductsByCategory = (categoryId: string): Product[] => {
  return PRODUCTS_CATALOG.filter((p) => p.category === categoryId);
};

export const getProductById = (id: string): Product | undefined => {
  return PRODUCTS_CATALOG.find((p) => p.id === id);
};

export const searchProducts = (query: string): Product[] => {
  const q = query.toLowerCase().trim();
  if (!q) return [];
  return PRODUCTS_CATALOG.filter(
    (p) =>
      p.name.toLowerCase().includes(q) ||
      p.banglaName.toLowerCase().includes(q) ||
      p.categoryName.toLowerCase().includes(q) ||
      p.shortDescription.toLowerCase().includes(q)
  );
};
